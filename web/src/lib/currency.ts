const FALLBACK = 'USD'

/** The currency of `locale`'s region, if it's one of `currencies`; otherwise USD. */
export function defaultCurrency(locale: string, currencies: readonly string[]): string {
  let region: string | undefined
  try {
    region = new Intl.Locale(locale).maximize().region
  } catch {
    return FALLBACK
  }
  const currency = region === undefined ? undefined : BY_REGION[region]
  return currency !== undefined && currencies.includes(currency) ? currency : FALLBACK
}
